// Installs the HUD into the Claude Code config directory and points the user's statusLine at it, or puts back what
// was there. hud.ts and what it imports are bundled into one file there, so the installed HUD does not depend on this
// repository staying where it is; reinstall after changing statusline/.
//   bun statusline/install.ts              install (backs up settings.json, keeps the old statusLine for --uninstall)
//   bun statusline/install.ts --uninstall  restore the statusLine that was there before install, remove the HUD file
//   bun statusline/install.ts --print      print the statusLine value without writing anything
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE = resolve(dirname(fileURLToPath(import.meta.url)), 'hud.ts')
const CONFIG_DIR = process.env.CLAUDE_CONFIG_DIR ?? join(homedir(), '.claude')
const SETTINGS = join(CONFIG_DIR, 'settings.json')
const PREVIOUS = join(CONFIG_DIR, 'statusline-hud.previous.json')
// .mjs so Node reads the ESM bundle too; bun runs it either way.
const TARGET = join(CONFIG_DIR, 'statusline-hud.mjs')
// Countdowns (rate-limit resets, prompt-cache expiry) are drawn in minutes, and event triggers go quiet while the
// session idles, so a 60s tick keeps them current for one ~10ms run a minute.
const REFRESH_SECONDS = 60

if (!process.versions.bun) {
  console.error('run this with bun: it bundles the HUD with Bun.build')
  process.exit(2)
}

const mode = process.argv[2] ?? 'install'
const value = { type: 'command', command: `${quote(runtime())} ${quote(TARGET)}`, padding: 0, refreshInterval: REFRESH_SECONDS }

if (mode === '--print') {
  console.log(JSON.stringify({ statusLine: value }, null, 2))
} else if (mode === '--uninstall') {
  uninstall()
} else if (mode === 'install') {
  await install()
} else {
  console.error(`unknown option ${mode}; use --print or --uninstall`)
  process.exit(2)
}

async function install(): Promise<void> {
  const built = await Bun.build({ entrypoints: [SOURCE], target: 'node', format: 'esm' })
  const bundle = built.outputs[0]
  if (!built.success || !bundle) {
    for (const log of built.logs) console.error(String(log))
    process.exit(1)
  }
  mkdirSync(CONFIG_DIR, { recursive: true })
  writeFileSync(TARGET, `// Generated by statusline/install.ts from ${SOURCE}; edit there and reinstall.\n${await bundle.text()}`)
  const settings = read()
  const current = settings.statusLine
  // A reinstall keeps the first backup and saved value, so --uninstall still returns to the pre-HUD statusLine.
  if (!isOurs(current)) {
    writeFileSync(PREVIOUS, JSON.stringify({ statusLine: current ?? null }, null, 2) + '\n')
    if (existsSync(SETTINGS)) copyFileSync(SETTINGS, `${SETTINGS}.hud-backup`)
  }
  write({ ...settings, statusLine: value })
  console.log(`installed: ${TARGET}`)
  console.log(`statusLine -> ${value.command}`)
  if (existsSync(`${SETTINGS}.hud-backup`)) console.log(`backup: ${SETTINGS}.hud-backup`)
  console.log('undo: bun statusline/install.ts --uninstall')
}

function uninstall(): void {
  const settings = read()
  if (!isOurs(settings.statusLine)) {
    console.log('statusLine is not the HUD; nothing changed')
    return
  }
  const saved = existsSync(PREVIOUS) ? (JSON.parse(readFileSync(PREVIOUS, 'utf8')) as { statusLine?: unknown }).statusLine : null
  const next = { ...settings }
  if (saved) next.statusLine = saved
  else delete next.statusLine
  write(next)
  rmSync(PREVIOUS, { force: true })
  rmSync(TARGET, { force: true })
  console.log(saved ? 'statusLine restored to the value before install' : 'statusLine removed')
}

function read(): Record<string, unknown> {
  return existsSync(SETTINGS) ? (JSON.parse(readFileSync(SETTINGS, 'utf8')) as Record<string, unknown>) : {}
}

function write(settings: Record<string, unknown>): void {
  writeFileSync(SETTINGS, JSON.stringify(settings, null, 2) + '\n')
}

function isOurs(statusLine: unknown): boolean {
  const command = (statusLine as { command?: unknown } | undefined)?.command
  return typeof command === 'string' && command.includes('statusline-hud.mjs')
}

// The absolute path, so the command works whatever PATH the session was started with. A symlink like
// /opt/homebrew/bin/bun survives upgrades, where process.execPath would name one versioned install.
function runtime(): string {
  return spawnSync('/bin/sh', ['-c', 'command -v bun'], { encoding: 'utf8' }).stdout.trim() || 'bun'
}

function quote(path: string): string {
  return /^[\w./-]+$/.test(path) ? path : `'${path.replace(/'/g, `'\\''`)}'`
}
